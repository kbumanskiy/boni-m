// Похожие начертания: где буква и цифра выглядят одинаково.
//
// Повод — замечание радиолюбителя с форума QRZ.RU (16 августа 2026):
// «очень похожие начертания 3 и З, не все догадаются, где буква, а где цифра».
// Он прав, и дело не в шрифте: в большинстве шрифтов эти знаки почти совпадают,
// а коды у них разные (З = --.., 3 = ...--). Ошибиться в занятии обидно вдвойне:
// человек решит, что не расслышал, хотя он не понял, что ему показали.
//
// Решение — подпись под знаком, но ТОЛЬКО у спорных. Подписывать все буквы подряд
// значит замусорить экран ради двух случаев в алфавите.

// Пар две, и это решение Кости от 17 августа 2026. Первая версия подписывала
// ещё 0/О/O, 1/I, 2/Z, 4/Ч, 5/S, 8/B — и сразу вылезло, чем это плохо: в английском
// режиме под латинской «S» появлялось слово «буква», о чём и написали с форума
// (R7CL) — а S и 5 не похожи вовсе. Подпись под каждым вторым знаком — шум,
// который мешает как раз тем, кто занимается всерьёз. Осталось то, что путают
// на самом деле: З с тройкой и О с нулём.
// Пара осталась одна — З и 3. Ноль ушёл отсюда 18 августа 2026: его теперь показываем
// перечёркнутым (Ø), и путать с буквой «О» стало нечего. Подсказал радиолюбитель
// с форума QRZ.RU: «Вместо цифры ноль можно писать Ø. Тогда и О не надо будет
// подписывать, что это буква». Так ноль пишут в радиограммах и на бланках — это
// не выдумка, а обычай службы связи, и он снимает проблему без единого слова подписи.
const TWINS = {
  '3': ['З'],
};

const DIGITS = new Set(Object.keys(TWINS));
const LETTERS = new Set(Object.values(TWINS).flat());

// Что подписать под знаком. Пустая строка — подпись не нужна.
// Возвращаем готовое слово, а не признак: подпись должна быть одна и та же
// всюду, где знак показан, иначе «цифра» в одном месте и «цифр.» в другом.
export function glyphKind(ch) {
  const c = String(ch ?? '');
  if (DIGITS.has(c)) return 'цифра';
  if (LETTERS.has(c)) return 'буква';
  return '';
}

// Спорен ли знак вообще — на случай, если понадобится проверить без подписи.
export function isAmbiguous(ch) {
  return glyphKind(ch) !== '';
}

// ——— Как знак выглядит на экране ———
// Ноль показываем перечёркнутым: Ø. Внутри у него по-прежнему обычный '0' — сравнение
// ответов, прогресс и резервные копии не должны знать про начертание. Иначе в прогрессе
// завёлся бы второй, «перечёркнутый» ноль, и заслуженное по нему пропало бы.
export function glyphText(ch) {
  return ch === '0' ? 'Ø' : String(ch ?? '');
}

// Как назвать знак словами — для разбора и для тех, кто видит Ø впервые.
export function glyphName(ch) {
  return ch === '0' ? 'ноль' : '';
}
