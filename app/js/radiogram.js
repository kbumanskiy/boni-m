// Контрольная радиограмма — приём групп по пять знаков.
//
// Это упражнение, по которому радисты сдают на разряд, и мы делаем его по официальным
// правилам, а не «примерно так». Источник — Правила вида спорта «радиоспорт»
// (приказ Минспорта России от 28.03.2022 № 230), статья 18 «Приём радиограмм»:
//
//   • тексты НЕСМЫСЛОВЫЕ: буквенные — из букв, цифровые — из десяти цифр,
//     смешанные — из букв, цифр и знаков препинания;
//   • «Знаки радиограммы объединяются в группы по пять знаков. Рядом в группе
//     могут находиться не более двух одинаковых знаков»;
//   • «Трансляция радиограммы каждой скорости ведётся в течение 1 мин»;
//   • «с повышением скорости на 10 знаков в минуту»;
//   • «Радиограмма считается принятой, если в её переписанном тексте допущено
//     не более пяти ошибок»;
//   • результат за радиограмму = скорость минус число ошибок.
//
// Просил об этом упражнении и радиолюбитель письмом (UA5B): «Хочу принимать
// на клавиатуре несмысловые тексты типа ASDFG HJKLL QWERT YUIOP ZXCVB в течение
// минуты и затем видеть свой результат и ошибки».

export const GROUP_SIZE = 5;
export const SPEED_STEP = 10;      // шаг повышения скорости, зн/мин (ст. 18)
export const MAX_ERRORS = 5;       // до пяти ошибок радиограмма считается принятой
export const MINUTE = 60;          // длительность полной радиограммы, секунд

// Знаки препинания смешанного текста — ровно те, что названы в правилах.
export const MIXED_PUNCT = ['.', ',', '/', '?', '='];

// Сколько групп прозвучит за отведённое время на данной скорости.
// Скорость в правилах — знаков в минуту, поэтому число знаков считается прямо.
export function groupsFor(cpm, seconds = MINUTE) {
  const chars = Math.round((cpm * seconds) / MINUTE);
  return Math.max(1, Math.round(chars / GROUP_SIZE));
}

// Собрать радиограмму. alphabet — массив знаков, из которых её составляют;
// rnd — источник случайности (по умолчанию Math.random), чтобы тест был повторяемым.
//
// Правило «не более двух одинаковых рядом» соблюдаем СКВОЗЬ границы групп: в правилах
// сказано «рядом в группе», но пауза между группами слышна как обычная межзнаковая,
// и три одинаковых знака подряд на слух остаются той же ловушкой, где бы они ни стояли.
// Строже правил — но не мягче, а это единственное направление, в котором можно ошибаться.
export function makeRadiogram(alphabet, groups, rnd = Math.random) {
  const set = [...alphabet];
  if (!set.length || groups < 1) return '';
  const out = [];
  for (let i = 0; i < groups * GROUP_SIZE; i++) {
    let ch;
    let guard = 0;
    do {
      ch = set[Math.floor(rnd() * set.length)];
      guard++;
      // Защита от вечного цикла на крошечном наборе (в тестах бывает набор из одного знака).
    } while (guard < 50 && out.length >= 2 && out[out.length - 1] === ch && out[out.length - 2] === ch);
    out.push(ch);
  }
  return out.join('').replace(new RegExp(`(.{${GROUP_SIZE}})`, 'g'), '$1 ').trim();
}

// Привести написанное человеком к сравнимому виду: заглавные, без пробелов и переносов.
// Разбивку на группы не сверяем: по правилам ошибкой считается неверный ЗНАК,
// а не то, где человек поставил пробел. Кириллическую раскладку не трогаем —
// в русском курсе радиограмма и составляется из русских букв.
export function normalize(text) {
  return String(text ?? '').toUpperCase()
    .replace(/\s+/g, '')
    .replace(/[ØøΘ]/g, '0');  // ноль показываем перечёркнутым, а печатают его обычным
}

// Сверка принятого с переданным.
//
// Считать «знак против знака по местам» нельзя: один пропущенный знак сдвинул бы
// весь остаток, и человек с одной опиской получил бы шестьдесят ошибок вместо одной.
// Поэтому выравниваем последовательности (расстояние Левенштейна с восстановлением пути):
// пропуск, лишний знак и замена — по одной ошибке каждый, ровно как считает судья.
export function compare(sent, received) {
  const a = [...normalize(sent)];
  const b = [...normalize(received)];
  const n = a.length, m = b.length;

  // d[i][j] — цена приведения первых i знаков переданного к первым j принятого.
  const d = Array.from({ length: n + 1 }, () => new Uint32Array(m + 1));
  for (let i = 0; i <= n; i++) d[i][0] = i;
  for (let j = 0; j <= m; j++) d[0][j] = j;
  for (let i = 1; i <= n; i++) {
    for (let j = 1; j <= m; j++) {
      const same = a[i - 1] === b[j - 1];
      d[i][j] = Math.min(
        d[i - 1][j - 1] + (same ? 0 : 1),  // замена (или совпадение)
        d[i - 1][j] + 1,                   // знак пропущен
        d[i][j - 1] + 1,                   // знак лишний
      );
    }
  }

  // Обратный ход: собираем разбор от конца к началу.
  const cells = [];
  let i = n, j = m;
  while (i > 0 || j > 0) {
    const same = i > 0 && j > 0 && a[i - 1] === b[j - 1];
    if (i > 0 && j > 0 && d[i][j] === d[i - 1][j - 1] + (same ? 0 : 1)) {
      cells.push(same
        ? { type: 'ok', expected: a[i - 1], got: b[j - 1] }
        : { type: 'wrong', expected: a[i - 1], got: b[j - 1] });
      i--; j--;
    } else if (i > 0 && d[i][j] === d[i - 1][j] + 1) {
      cells.push({ type: 'missed', expected: a[i - 1], got: '' }); // не расслышал
      i--;
    } else {
      cells.push({ type: 'extra', expected: '', got: b[j - 1] });  // лишний знак
      j--;
    }
  }
  cells.reverse();

  const errors = cells.filter((c) => c.type !== 'ok').length;
  return { errors, cells, total: n, correct: cells.filter((c) => c.type === 'ok').length };
}

// Радиограмма принята? (ст. 18: не более пяти ошибок)
export function accepted(errors) {
  return errors <= MAX_ERRORS;
}

// Очки за радиограмму: скорость минус ошибки, но не ниже нуля.
export function score(cpm, errors) {
  return Math.max(0, Math.round(cpm) - errors);
}

// Следующая скорость — на десять знаков быстрее (ст. 18).
export function nextSpeed(cpm, max = Infinity) {
  return Math.min(max, Math.round(cpm) + SPEED_STEP);
}
