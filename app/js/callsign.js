// Свой позывной на слух (ТЗ §9) — теперь настоящий, а не один на всех.
//
// Повод — вопрос с форума QRZ.RU 18 августа 2026: «"Принять свой позывной" — почему-то
// Boney M. У меня не такой позывной ;)». И правда: позывной спрашивали при первом запуске,
// сохраняли в профиль — а в упражнении всё равно звучал «Boney M», позывной папы.
// Теперь звучит то, что человек ввёл, а «Boney M» остаётся лишь значением по умолчанию.
//
// Главная тонкость — СРАВНЕНИЕ ИДЁТ ПО КОДАМ, а не по буквам. Позывные пишутся латиницей
// (RA9FLC), а курс у нас чаще русский. Код у Б и B один и тот же, у О и O — тоже, поэтому
// человек, освоивший русские буквы, свой латинский позывной уже умеет принимать. Сравнивай
// мы буквы — упражнение не открылось бы никогда.

// Позывной: буквы (латиница и кириллица), цифры, дробная черта (RA9FLC/9, R7CL/P)
// и пробел. Пробел разрешён только ради написания: у папы позывной записан «Boney M»,
// и терять привычный вид из-за упражнения незачем. Прозвучать он всё равно не может —
// кода у пробела нет, и в callsignParts он отпадает сам.
// Всё прочее выбрасываем молча: в поле ввода легко занести скобку или запятую.
const ALLOWED = /[A-ZА-ЯЁ0-9/ ]/;
const MAX_LEN = 12; // самые длинные позывные с приставками укладываются с запасом

export function normalizeCallsign(raw) {
  return [...String(raw ?? '').toUpperCase()]
    .filter((c) => ALLOWED.test(c))
    .join('')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, MAX_LEN);
}

// Знаки позывного с их кодами. lookup(ch) → код или undefined.
// Знак без кода (например дробная черта, если её нет в таблице) отбрасывается:
// проиграть его нечем, а спотыкаться о него упражнение не должно.
export function callsignParts(raw, lookup) {
  return [...normalizeCallsign(raw)]
    .map((ch) => ({ ch, code: lookup(ch) }))
    .filter((p) => typeof p.code === 'string' && p.code.length > 0);
}

// Доступно ли упражнение: все коды позывного должны быть среди уже освоенных.
// learnedCodes — множество (Set) кодов освоенных знаков текущего курса.
export function callsignAvailable(raw, lookup, learnedCodes) {
  const parts = callsignParts(raw, lookup);
  if (!parts.length) return false;
  return parts.every((p) => learnedCodes.has(p.code));
}
